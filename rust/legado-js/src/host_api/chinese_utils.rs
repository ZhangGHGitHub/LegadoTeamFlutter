/// 繁体→简体 映射表
static T2S_MAP: LazyLock<HashMap<char, char>> = LazyLock::new(|| {
    let mut map = HashMap::new();
    for pair in T2S_PAIRS.split_whitespace() {
        let chars: Vec<char> = pair.chars().collect();
        if chars.len() == 2 && chars[0] != chars[1] {
            map.insert(chars[0], chars[1]);
        }
    }
    map
});

/// 简体→繁体 映射表（反向）
static S2T_MAP: LazyLock<HashMap<char, char>> = LazyLock::new(|| {
    T2S_MAP.iter().map(|(&t, &s)| (s, t)).collect()
});

/// t2s(text) — 繁体转简体
///
/// 对应 Kotlin: `ChineseUtils.t2s(content)`
/// 使用内置映射表逐字替换
pub fn t2s(text: &str) -> String {
    text.chars()
        .map(|c| T2S_MAP.get(&c).copied().unwrap_or(c))
        .collect()
}

/// s2t(text) — 简体转繁体
///
/// 对应 Kotlin: `ChineseUtils.s2t(content)`
/// 使用反向映射表逐字替换
pub fn s2t(text: &str) -> String {
    text.chars()
        .map(|c| S2T_MAP.get(&c).copied().unwrap_or(c))
        .collect()
}

