    #[test]
    fn test_s2t_sentence() {
        assert_eq!(s2t("中华人民共和国"), "中華人民共和國");
    }

    #[test]
    fn test_roundtrip_common() {
        // 对于映射表中一一对应的字，往返转换应还原
        // 注意: 部分字存在多对一映射，往返可能不完全还原
        let original = "國學書門東車風";
        let simplified = t2s(original);
        let back = s2t(&simplified);
        assert_eq!(back, original);
    }

    #[test]
    fn test_mixed_text() {
        // 非映射字符保持不变
        assert_eq!(t2s("Hello World 123"), "Hello World 123");
        assert_eq!(t2s("繁體English混合"), "繁体English混合");
    }

    #[test]
    fn test_empty_string() {
        assert_eq!(t2s(""), "");
        assert_eq!(s2t(""), "");
    }
